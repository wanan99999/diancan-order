-- ========== 用户资料 ==========
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  uid bigint generated always as identity (start with 100001) unique,  -- 注册后固定的数字ID
  username text unique not null,
  nickname text not null,
  avatar_url text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

-- 注册时自动建资料（一律非管理员）
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, nickname)
  values (new.id,
          coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)),
          coalesce(nullif(new.raw_user_meta_data->>'nickname', ''), new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)));
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

alter table public.profiles enable row level security;
drop policy if exists "profiles read" on public.profiles;
create policy "profiles read" on public.profiles for select
  using (id = auth.uid() or public.is_admin());
drop policy if exists "profiles update self" on public.profiles;
create policy "profiles update self" on public.profiles for update
  using (id = auth.uid()) with check (id = auth.uid());
-- 用户只能改昵称和头像（不能改 is_admin / uid / username）
revoke update on public.profiles from anon, authenticated;
grant update (nickname, avatar_url) on public.profiles to authenticated;

-- ========== 菜品 ==========
create table if not exists public.dishes (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  category text not null,
  spicy smallint not null default 0 check (spicy between 0 and 3),
  featured boolean not null default false,
  emoji text,
  image_url text,
  sort int not null default 0,
  created_at timestamptz not null default now()
);
alter table public.dishes enable row level security;
drop policy if exists "dishes read" on public.dishes;
create policy "dishes read" on public.dishes for select using (true);
drop policy if exists "dishes admin write" on public.dishes;
create policy "dishes admin write" on public.dishes for all
  using (public.is_admin()) with check (public.is_admin());

-- ========== 订单 ==========
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_no text not null unique,
  user_id uuid not null references public.profiles(id) on delete cascade default auth.uid(),
  items jsonb not null,            -- 下单时的菜品快照
  item_count int not null,
  total numeric(10,2) not null,
  people int not null default 1 check (people between 1 and 50),
  remark text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists orders_user_idx on public.orders(user_id, created_at desc);
alter table public.orders enable row level security;
drop policy if exists "orders read" on public.orders;
create policy "orders read" on public.orders for select
  using (user_id = auth.uid() or public.is_admin());
drop policy if exists "orders insert self" on public.orders;
create policy "orders insert self" on public.orders for insert
  with check (user_id = auth.uid());

-- ========== 图片存储 ==========
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('images', 'images', true, 2097152, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true;

drop policy if exists "images upload" on storage.objects;
create policy "images upload" on storage.objects for insert to authenticated
  with check (bucket_id = 'images' and (
    ((storage.foldername(name))[1] = 'avatars' and (storage.foldername(name))[2] = auth.uid()::text)
    or ((storage.foldername(name))[1] = 'dishes' and public.is_admin())
  ));

-- ========== Data API 权限（不依赖"自动暴露新表"设置） ==========
grant usage on schema public to anon, authenticated;
grant select on public.dishes to anon, authenticated;
grant insert, update, delete on public.dishes to authenticated;
grant select on public.profiles to authenticated;
grant select, insert on public.orders to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.is_admin() to anon, authenticated;

